package pins

import (
	"bytes"
	"strings"
	"testing"
)

func TestLockDeterministic(t *testing.T) {
	t.Parallel()
	pure := Locked{
		Name: "Six", Version: "1.17.0", Why: "pinned by upstream",
		Files: []File{{Name: "six-1.17.0-py2.py3-none-any.whl", SHA256: strings.Repeat("6", 64)}},
	}
	built := Locked{
		Name: "PyYAML", Version: "6.0.3", Why: "pinned by upstream", FromSource: true,
		Files: []File{{Name: "pyyaml-6.0.3.tar.gz", SHA256: strings.Repeat("9", 64)}},
	}
	cryptography := Locked{
		Name: "cryptography", Version: "50.0.2", Why: "pins.txt: upstream leaves it unpinned (>=3.0)", FromSource: true,
		Files: []File{{Name: "cryptography-50.0.2.tar.gz", SHA256: strings.Repeat("c", 64)}},
	}
	lock := func(pkgs ...Locked) string {
		var b bytes.Buffer
		if err := WriteLock(&b, Lock{Header: []string{"Generated by go run ./cmd/divbast-pins.", "Do not edit."}, Packages: pkgs}); err != nil {
			t.Fatal(err)
		}
		return b.String()
	}
	first, second := lock(pure, built, cryptography), lock(cryptography, pure, built)
	if first != second {
		t.Errorf("the same packages in another order gave another lock:\n%s\n---\n%s", first, second)
	}
	want := `# Generated by go run ./cmd/divbast-pins.
# Do not edit.
--no-binary cryptography,pyyaml

# pins.txt: upstream leaves it unpinned (>=3.0); built from source
cryptography==50.0.2 \
    --hash=sha256:` + strings.Repeat("c", 64) + `

# pinned by upstream; built from source
pyyaml==6.0.3 \
    --hash=sha256:` + strings.Repeat("9", 64) + `

# pinned by upstream
six==1.17.0 \
    --hash=sha256:` + strings.Repeat("6", 64) + `
`
	if first != want {
		t.Errorf("WriteLock() =\n%s\nwant\n%s", first, want)
	}
	// With nothing built from source, no --no-binary line
	if got := lock(pure); strings.Contains(got, "--no-binary") {
		t.Errorf("WriteLock() of pure wheels alone =\n%s\nwant no --no-binary line", got)
	}
}
